/// Every country for the phone-number pickers: ISO 3166-1 alpha-2 code, the
/// E.164 calling code (with the area code for the +1 islands), and the English
/// and Arabic names. The backend takes any E.164 number (`^\+[1-9]\d{7,14}$`).
class Country {
  const Country(this.iso, this.dial, this.en, this.ar);

  final String iso;
  final String dial;
  final String en;
  final String ar;

  /// The flag emoji built from the two regional-indicator letters of [iso].
  String get flag => String.fromCharCodes(
    iso.toUpperCase().codeUnits.map((c) => 0x1F1E6 + c - 0x41),
  );

  String name(bool arabic) => arabic ? ar : en;
}

