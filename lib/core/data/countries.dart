/// The country to show for [dial]: [preferIso] when it has that code (so Canada
/// stays Canada though the US shares +1), else the first popular one, else the first.
Country? countryForDial(String dial, {String? preferIso}) {
  if (preferIso != null) {
    for (final c in countries) {
      if (c.iso == preferIso && c.dial == dial) return c;
    }
  }
  for (final iso in popularCountryIsos) {
    final c = countries.firstWhere((c) => c.iso == iso);
    if (c.dial == dial) return c;
  }
  for (final c in countries) {
    if (c.dial == dial) return c;
  }
  return null;
}

/// The longest calling code [e164] starts with ("+1876…" → "+1876", "+20…" → "+20"); '' if none.
String dialPrefixOf(String e164) {
  var best = '';
  for (final c in countries) {
    if (c.dial.length > best.length && e164.startsWith(c.dial)) best = c.dial;
  }
  return best;
}
